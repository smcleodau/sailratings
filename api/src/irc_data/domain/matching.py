@dataclass(frozen=True)
class CandidatePairV1:
    """One identity candidate: two canonical entities flagged as possible
    duplicates, with the full explanation of *why*.

    ``left_id`` / ``right_id``
        DP-03-01 opaque entity ids (``boat_01J4Z…``).  The pair key is
        normalised order-independently, so the pair (A, B) and (B, A) are
        the same candidate.
    ``features``
        The compared attributes — the human-readable justification.
    ``score``
        Aggregate similarity in [0, 1].
    ``model_version`` / ``rule_version``
        Exactly which scorer/blocker produced this candidate.  At least
        one must be set: a candidate with no version is unexplained.
    """

    entity_type: str
    left_id: str
    right_id: str
    features: tuple[FeatureScoreV1, ...] = ()
    score: float = 0.0
    model_version: str | None = None
    rule_version: str | None = None
    generated_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    status: str = CandidateStatus.OPEN.value
    metadata: dict[str, Any] = field(default_factory=dict)
    candidate_id: str = ""
    schema_version: str = SCHEMA_VERSION

    def __post_init__(self) -> None:
        if not self.entity_type:
            raise MatchDecisionError("entity_type is required")
        if not self.left_id or not self.right_id:
            raise MatchDecisionError("both left_id and right_id are required")
        if self.left_id == self.right_id:
            raise MatchDecisionError("a candidate pair must reference two distinct entities")
        if not (0.0 <= float(self.score) <= 1.0):
            raise MatchDecisionError(f"score must be in [0, 1], got {self.score!r}")
        if not self.model_version and not self.rule_version:
            raise MatchDecisionError(
                "a candidate must name its model_version and/or rule_version — "
                "an unexplained candidate is not actionable"
            )
        object.__setattr__(self, "generated_at", _utc(self.generated_at))
        object.__setattr__(self, "features", tuple(self.features))
        if not self.candidate_id:
            object.__setattr__(self, "candidate_id", self._derive_id())

    # -- Identity --------------------------------------------------------------

    @property
    def pair_key(self) -> tuple[str, str]:
        """Order-independent key so (A, B) ≡ (B, A)."""
        return tuple(sorted((self.left_id, self.right_id)))  # type: ignore[return-value]

    def _derive_id(self) -> str:
        return _content_id(
            "cand",
            {
                "schema_version": self.schema_version,
                "entity_type": self.entity_type,
                "pair_key": self.pair_key,
                "score": float(self.score),
                "features": [f.to_dict() for f in self.features],
                "model_version": self.model_version,
                "rule_version": self.rule_version,
                "generated_at": _dt_to_iso(self.generated_at),
            },
        )

    # -- Serialisation ---------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "candidate_id": self.candidate_id,
            "entity_type": self.entity_type,
            "left_id": self.left_id,
            "right_id": self.right_id,
            "pair_key": list(self.pair_key),
            "features": [f.to_dict() for f in self.features],
            "score": float(self.score),
            "model_version": self.model_version,
            "rule_version": self.rule_version,
            "generated_at": _dt_to_iso(self.generated_at),
            "status": self.status,
            "metadata": self.metadata or {},
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), sort_keys=True)

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> "CandidatePairV1":
        return cls(
            schema_version=d.get("schema_version", SCHEMA_VERSION),
            candidate_id=d.get("candidate_id", ""),
            entity_type=d["entity_type"],
            left_id=d["left_id"],
            right_id=d["right_id"],
            features=tuple(FeatureScoreV1.from_dict(f) for f in d.get("features", ())),
            score=float(d.get("score", 0.0)),
            model_version=d.get("model_version"),
            rule_version=d.get("rule_version"),
            generated_at=_dt_from_iso(d["generated_at"]) if d.get("generated_at") else datetime.now(timezone.utc),
            status=d.get("status", CandidateStatus.OPEN.value),
            metadata=dict(d.get("metadata") or {}),
        )

    @classmethod
    def from_json(cls, s: str) -> "CandidatePairV1":
        return cls.from_dict(json.loads(s))


