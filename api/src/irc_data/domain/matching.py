"""Identity candidate and match-decision contracts (DP-04-01).

Goal: **make entity resolution explainable and reversible.**

This module is the *code of record* for how the platform talks about
"these two entities might be the same thing" and what it decided to do
about it.  It defines two immutable, JSON-round-trippable contracts:

* :class:`CandidatePairV1` — one *identity candidate*: a pair of canonical
  entities (DP-03-01 opaque ids) that blocking/scoring flagged as
  potential duplicates, together with the **features** that were compared,
  the **score**, and the **model/rule version** that produced it.
* :class:`MatchDecisionV1` — one *match decision* about a candidate pair:
  the **decision** (``match`` | ``non_match`` | ``uncertain`` | ``split``),
  the **actor** that decided (auto rule, model version, or human steward),
  the **threshold/policy** the decision was taken under, the **evidence**
  it rests on, the **timestamp**, and the **supersession** chain that
  makes every decision reversible without deleting anything.

Design invariants
-----------------

1. **No merge without stored evidence and threshold/policy.**
   :func:`apply_decision` is the only sanctioned bridge from a decision
   to the entity registry.  It refuses to merge unless the decision
   carries at least one :class:`EvidenceRef` *and* a non-empty
   ``threshold_policy``, and it *also* mechanically re-checks auto-rule
   scores against the named :class:`MatchPolicy`'s merge threshold — a
   decision that says "match" but whose score is below the policy's
   threshold is rejected, so the gate cannot be bypassed by asserting a
   verdict without the numbers to back it.

2. **Decisions are never mutated or deleted.**  A wrong decision is
   corrected by appending a *new* decision whose ``supersedes`` pointer
   names the old one (:func:`reverse_decision` / ``MatchJournal.reverse``).
   The old row stays in the journal with its ``superseded_by`` link —
   exactly the DP-03-02 assertion supersession semantics, lifted one
   level up from facts to identity decisions.

3. **Reversal never deletes source assertions.**  Reversing a merge uses
   the entity registry's :meth:`DomainModel.split`, which moves the
   *named* assertion references onto a resurrected entity stamped
   ``split_from``.  The original ``AssertionV1`` rows are re-keyed, not
   deleted (they remain content-addressed and immutable per DP-03-02),
   and the registry's append-only ``RegistryEvent`` log keeps both the
   merge and the split, so the pre-decision state is reconstructable for
   any system time.

4. **Everything is explainable.**  A decision answers, from its own
   fields alone: *which two entities* (``candidate.left_id`` /
   ``right_id``), *why they were compared* (``candidate.features``),
   *how strongly the evidence pointed* (``candidate.score`` and the
   feature weights), *under which logic* (``candidate.model_version`` /
   ``rule_version``), *who decided* (``actor``), *when* (``decided_at``),
   *under which policy* (``threshold_policy``), *on what evidence*
   (``evidence``), and *what became of the decision* (``superseded_by`` /
   ``reversal_of``).

Downstream handoff
------------------

* The **matching engine** (``irc_data.matching``) emits
  :class:`CandidatePairV1` records; it never merges.
* The **auto-decider / steward UI** turns candidates into
  :class:`MatchDecisionV1` records via :func:`decide` (which validates
  against a :class:`MatchPolicy`).
* The **registry bridge** calls :func:`apply_decision`; uncertainty is
  never a merge, ``split`` decisions require ``split_assertion_ids``.
* The **journal** (:class:`MatchJournal`) is the append-only store;
  ``decision_as_of(t)`` reproduces the effective decision state for any
  prior system time.
"""

