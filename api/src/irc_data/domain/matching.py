class MatchDecisionError(ValueError):
    """Base class for match-contract violations."""


class MissingEvidenceError(MatchDecisionError):
    """A merge was attempted without stored evidence."""


class MissingPolicyError(MatchDecisionError):
    """A decision was taken without naming its threshold/policy."""


class BelowThresholdError(MatchDecisionError):
    """An auto/rule ``match`` decision's score is below the policy threshold."""


class DecisionStateError(MatchDecisionError):
    """The decision cannot be applied/reversed in the journal's state."""


# ---------------------------------------------------------------------------
# Helpers (same conventions as irc_data.assertions.models)
# ---------------------------------------------------------------------------


def _utc(dt: datetime) -> datetime:
    """Normalise a datetime to aware-UTC (naive assumed UTC)."""
    if dt.tzinfo is None:
        return dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


def _dt_to_iso(dt: datetime | None) -> str | None:
    if dt is None:
        return None
    return _utc(dt).isoformat()


def _dt_from_iso(s: str | datetime | None) -> datetime | None:
    if s is None:
        return None
    if isinstance(s, datetime):
        return _utc(s)
    return _utc(datetime.fromisoformat(s))


def _canonical_json(payload: Any) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str)


def _content_id(prefix: str, payload: Mapping[str, Any]) -> str:
    """Deterministic content-addressed id: ``<prefix>_<sha256[:24]>``."""
    digest = hashlib.sha256(_canonical_json(payload).encode("utf-8")).hexdigest()
    return f"{prefix}_{digest[:24]}"


