@dataclass(frozen=True)
class FeatureScoreV1:
    """One compared attribute of a candidate pair.

    Features are the *explainability payload*: each names the attribute
    compared (``sail_number``, ``boat_name``, ``design`` …), the two
    observed values, the similarity computed, and the weight that
    similarity carried in the pair's aggregate score.
    """

    name: str
    value_left: Any = None
    value_right: Any = None
    #: Similarity in [0, 1]; ``None`` means "not comparable / missing data".
    similarity: float | None = None
    #: Non-negative weight this feature contributed to the aggregate score.
    weight: float = 0.0

    def __post_init__(self) -> None:
        if not self.name:
            raise MatchDecisionError("feature name is required")
        if self.similarity is not None and not (0.0 <= float(self.similarity) <= 1.0):
            raise MatchDecisionError(
                f"feature {self.name!r}: similarity must be in [0, 1], "
                f"got {self.similarity!r}"
            )
        if float(self.weight) < 0.0:
            raise MatchDecisionError(
                f"feature {self.name!r}: weight must be >= 0, got {self.weight!r}"
            )

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "value_left": self.value_left,
            "value_right": self.value_right,
            "similarity": self.similarity,
            "weight": float(self.weight),
        }

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> "FeatureScoreV1":
        return cls(
            name=d["name"],
            value_left=d.get("value_left"),
            value_right=d.get("value_right"),
            similarity=d.get("similarity"),
            weight=float(d.get("weight", 0.0)),
        )


@dataclass(frozen=True)
class EvidenceRef:
    """A pointer to one piece of evidence a decision rests on.

    ``kind`` names the evidence class: ``assertion`` (a DP-03-02
    ``AssertionV1`` id), ``artifact`` (a DP-02-01 raw provenance
    envelope hash), ``registry_event`` (a prior merge/split log entry),
    ``certificate_ref`` / ``results_url`` … — free-form but required.
    ``ref`` is the id, hash or URL.  ``note`` records *why* the evidence
    supports the decision, so a reviewer never has to guess.
    """

    kind: str
    ref: str
    note: str = ""

    def __post_init__(self) -> None:
        if not self.kind:
            raise MatchDecisionError("evidence kind is required")
        if not self.ref:
            raise MatchDecisionError("evidence ref is required")

    def to_dict(self) -> dict[str, Any]:
        return {"kind": self.kind, "ref": self.ref, "note": self.note}

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> "EvidenceRef":
        return cls(kind=d["kind"], ref=d["ref"], note=d.get("note", ""))


@dataclass(frozen=True)
class MatchPolicy:
    """The threshold policy under which decisions are judged.

    A policy is *named and versioned* (``name``) so every decision can
    point at the exact rulebook it was taken under; when thresholds are
    tuned, the name changes and history stays attributable.

    ``merge_threshold``
        Minimum aggregate score for an auto/rule ``match`` to be
        **applied** as a merge.  Decisions at or above this score are
        auto-mergeable; below it, a claimed ``match`` from an auto actor
        is rejected at the gate.
    ``review_threshold``
        Floor of the *uncertain* band: scores in
        ``[review_threshold, merge_threshold)`` route to human review.
    ``non_match_threshold``
        Scores below this are auto-``non_match``-able.
    """

    name: str
    merge_threshold: float
    review_threshold: float = 0.0
    non_match_threshold: float = 0.0

    def __post_init__(self) -> None:
        if not self.name:
            raise MatchDecisionError("policy name is required")
        for label, v in (
            ("merge_threshold", self.merge_threshold),
            ("review_threshold", self.review_threshold),
            ("non_match_threshold", self.non_match_threshold),
        ):
            if not (0.0 <= float(v) <= 1.0):
                raise MatchDecisionError(f"{label} must be in [0, 1], got {v!r}")
        if not (self.non_match_threshold <= self.review_threshold <= self.merge_threshold):
            raise MatchDecisionError(
                "thresholds must satisfy "
                "non_match_threshold <= review_threshold <= merge_threshold"
            )

    # -- Verdict helpers ------------------------------------------------------

    def band_for_score(self, score: float) -> DecisionType:
        """The verdict band a bare score falls into under this policy."""
        if score >= self.merge_threshold:
            return DecisionType.MATCH
        if score < self.non_match_threshold:
            return DecisionType.NON_MATCH
        return DecisionType.UNCERTAIN

    def permits_auto_merge(self, score: float) -> bool:
        return score >= self.merge_threshold

    def permits_auto_non_match(self, score: float) -> bool:
        return score < self.non_match_threshold

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "merge_threshold": float(self.merge_threshold),
            "review_threshold": float(self.review_threshold),
            "non_match_threshold": float(self.non_match_threshold),
        }

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> "MatchPolicy":
        return cls(
            name=d["name"],
            merge_threshold=float(d["merge_threshold"]),
            review_threshold=float(d.get("review_threshold", 0.0)),
            non_match_threshold=float(d.get("non_match_threshold", 0.0)),
        )


#: The platform's default boat-identity policy.  Named + versioned; tuning
#: any threshold means minting a new name so history stays attributable.
DEFAULT_BOAT_POLICY = MatchPolicy(
    name="boat-merge-policy-v1",
    merge_threshold=0.90,
    review_threshold=0.50,
    non_match_threshold=0.20,
)


