@dataclass(frozen=True)
class MatchDecisionV1:
    """One immutable match decision about a candidate pair.

    Frozen: a decision, once recorded, never changes.  Correction is a
    *new* decision with ``supersedes`` pointing here (and
    ``reversal_of`` when the new decision undoes this one); this row
    gains a ``superseded_by`` link via :meth:`superseded`.
    """

    candidate: CandidatePairV1
    decision: str
    actor: str
    actor_kind: str
    threshold_policy: str
    evidence: tuple[EvidenceRef, ...] = ()
    decided_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    rationale: str = ""
    #: Assertion ids to move when ``decision == "split"``.
    split_assertion_ids: tuple[str, ...] = ()
    #: Supersession / reversal chain.
    supersedes: str | None = None
    superseded_by: str | None = None
    superseded_at: datetime | None = None
    reversal_of: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)
    id: str = ""
    schema_version: str = SCHEMA_VERSION

    def __post_init__(self) -> None:
        if self.decision not in DECISIONS:
            raise MatchDecisionError(
                f"decision must be one of {DECISIONS}, got {self.decision!r}"
            )
        if not self.actor:
            raise MatchDecisionError("actor is required — a decision must name who took it")
        if self.actor_kind not in tuple(a.value for a in ActorKind):
            raise MatchDecisionError(
                f"actor_kind must be one of {[a.value for a in ActorKind]}, "
                f"got {self.actor_kind!r}"
            )
        if not self.threshold_policy:
            raise MissingPolicyError(
                "threshold_policy is required — no decision is taken outside a policy"
            )
        if self.decision == DecisionType.SPLIT.value and not self.split_assertion_ids:
            raise MatchDecisionError(
                "a split decision must name split_assertion_ids — the registry "
                "needs to know exactly which assertion references move"
            )
        object.__setattr__(self, "decided_at", _utc(self.decided_at))
        if self.superseded_at is not None:
            object.__setattr__(self, "superseded_at", _utc(self.superseded_at))
        object.__setattr__(self, "evidence", tuple(self.evidence))
        object.__setattr__(self, "split_assertion_ids", tuple(self.split_assertion_ids))
        if not self.id:
            object.__setattr__(self, "id", self._derive_id())

    # -- Identity --------------------------------------------------------------

    def _derive_id(self) -> str:
        return _content_id(
            "dec",
            {
                "schema_version": self.schema_version,
                "candidate_id": self.candidate.candidate_id,
                "decision": self.decision,
                "actor": self.actor,
                "actor_kind": self.actor_kind,
                "threshold_policy": self.threshold_policy,
                "decided_at": _dt_to_iso(self.decided_at),
                "supersedes": self.supersedes,
                "reversal_of": self.reversal_of,
                "split_assertion_ids": list(self.split_assertion_ids),
                "evidence": [e.to_dict() for e in self.evidence],
            },
        )

    # -- State predicates --------------------------------------------------------

    @property
    def is_superseded(self) -> bool:
        return self.superseded_by is not None

    def known_at(self, as_of: datetime) -> bool:
        """True if the system knew of this decision at system time *as_of*."""
        return self.decided_at <= _utc(as_of)

    # -- Supersession ------------------------------------------------------------

    def superseded(self, successor: "MatchDecisionV1") -> "MatchDecisionV1":
        """Return a copy marked superseded by *successor* (bitemporal).

        The successor must point back via ``supersedes``.  ``superseded_at``
        is the successor's ``decided_at``, so a supersession only affects
        as-of views at or after the time the successor was decided — the
        view *before* the correction still shows this decision in force.
        """
        if successor.id == self.id:
            raise MatchDecisionError("a decision cannot supersede itself")
        if successor.supersedes != self.id:
            raise MatchDecisionError(
                "successor.supersedes must point at this decision's id"
            )
        return self._replace(
            superseded_by=successor.id,
            superseded_at=successor.decided_at,
        )

    def _replace(self, **changes: Any) -> "MatchDecisionV1":
        """frozen-dataclass replace that keeps the original decision id."""
        payload = self.to_dict()
        payload.update(changes)
        payload["decision_id"] = self.id  # id is identity, not content
        return MatchDecisionV1.from_dict(payload)

    # -- Serialisation ---------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "decision_id": self.id,
            "candidate": self.candidate.to_dict(),
            "decision": self.decision,
            "actor": self.actor,
            "actor_kind": self.actor_kind,
            "threshold_policy": self.threshold_policy,
            "evidence": [e.to_dict() for e in self.evidence],
            "decided_at": _dt_to_iso(self.decided_at),
            "rationale": self.rationale,
            "split_assertion_ids": list(self.split_assertion_ids),
            "supersedes": self.supersedes,
            "superseded_by": self.superseded_by,
            "superseded_at": _dt_to_iso(self.superseded_at),
            "reversal_of": self.reversal_of,
            "metadata": self.metadata or {},
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), sort_keys=True)

    @classmethod
    def from_dict(cls, d: Mapping[str, Any]) -> "MatchDecisionV1":
        return cls(
            schema_version=d.get("schema_version", SCHEMA_VERSION),
            id=d.get("decision_id", ""),
            candidate=CandidatePairV1.from_dict(d["candidate"]),
            decision=d["decision"],
            actor=d["actor"],
            actor_kind=d.get("actor_kind", ActorKind.AUTO_RULE.value),
            threshold_policy=d["threshold_policy"],
            evidence=tuple(EvidenceRef.from_dict(e) for e in d.get("evidence", ())),
            decided_at=_dt_from_iso(d["decided_at"]) if d.get("decided_at") else datetime.now(timezone.utc),
            rationale=d.get("rationale", ""),
            split_assertion_ids=tuple(d.get("split_assertion_ids") or ()),
            supersedes=d.get("supersedes"),
            superseded_by=d.get("superseded_by"),
            superseded_at=_dt_from_iso(d.get("superseded_at")),
            reversal_of=d.get("reversal_of"),
            metadata=dict(d.get("metadata") or {}),
        )

    @classmethod
    def from_json(cls, s: str) -> "MatchDecisionV1":
        return cls.from_dict(json.loads(s))


# ---------------------------------------------------------------------------
# decide() — build + validate a decision against a policy
# ---------------------------------------------------------------------------


def decide(
    candidate: CandidatePairV1,
    decision: DecisionType | str,
    *,
    actor: str,
    actor_kind: ActorKind | str,
    policy: MatchPolicy,
    evidence: Iterable[EvidenceRef] = (),
    decided_at: datetime | None = None,
    rationale: str = "",
    split_assertion_ids: Iterable[str] = (),
    supersedes: str | None = None,
    reversal_of: str | None = None,
    metadata: Mapping[str, Any] | None = None,
) -> MatchDecisionV1:
    """Create a :class:`MatchDecisionV1`, enforcing the decision contract.

    Validation rules (this is where policy meets the decision):

    * Every decision names its policy (``policy.name`` is stored as
      ``threshold_policy``).
    * An auto (rule/model) ``match`` whose candidate score is below
      ``policy.merge_threshold`` is rejected — a verdict cannot outrun
      the numbers under its own policy.  Human stewards may decide over
      the band, but the evidence requirement below still applies at the
      merge gate.
    * An auto ``non_match`` above ``policy.merge_threshold`` is rejected
      (symmetric sanity: the rule contradicts its own score).
    * ``split`` decisions must name ``split_assertion_ids`` (enforced by
      the dataclass as well).
    """
    decision_value = decision.value if isinstance(decision, DecisionType) else decision
    actor_kind_value = actor_kind.value if isinstance(actor_kind, ActorKind) else actor_kind

    if actor_kind_value in (ActorKind.AUTO_RULE.value, ActorKind.MODEL.value):
        if decision_value == DecisionType.MATCH.value and not policy.permits_auto_merge(
            candidate.score
        ):
            raise BelowThresholdError(
                f"auto match rejected: score {candidate.score:.3f} < "
                f"merge_threshold {policy.merge_threshold:.3f} of {policy.name!r}"
            )
        if decision_value == DecisionType.NON_MATCH.value and policy.permits_auto_merge(
            candidate.score
        ):
            raise BelowThresholdError(
                f"auto non_match rejected: score {candidate.score:.3f} >= "
                f"merge_threshold {policy.merge_threshold:.3f} of {policy.name!r}"
            )

    return MatchDecisionV1(
        candidate=candidate,
        decision=decision_value,
        actor=actor,
        actor_kind=actor_kind_value,
        threshold_policy=policy.name,
        evidence=tuple(evidence),
        decided_at=decided_at or datetime.now(timezone.utc),
        rationale=rationale,
        split_assertion_ids=tuple(split_assertion_ids),
        supersedes=supersedes,
        reversal_of=reversal_of,
        metadata=dict(metadata or {}),
    )


# ---------------------------------------------------------------------------
# The merge gate — no merge without stored evidence and threshold/policy
# ---------------------------------------------------------------------------


def _enforce_merge_gate(
    decision: MatchDecisionV1,
    policy: MatchPolicy | None,
) -> None:
    """Acceptance criterion, in code: *no merge occurs without stored
    evidence and threshold/policy*."""
    if not decision.evidence:
        raise MissingEvidenceError(
            f"merge of {decision.candidate.left_id!r} + "
            f"{decision.candidate.right_id!r} refused: the decision carries no "
            "stored evidence"
        )
    if not decision.threshold_policy:
        # MatchDecisionV1 already enforces this; kept explicit so the gate
        # reads as the acceptance criterion states it.
        raise MissingPolicyError("merge refused: no threshold/policy recorded")
    if policy is not None:
        if policy.name != decision.threshold_policy:
            raise MissingPolicyError(
                f"decision names policy {decision.threshold_policy!r} but was "
                f"applied under {policy.name!r}"
            )
        if decision.actor_kind in (ActorKind.AUTO_RULE.value, ActorKind.MODEL.value) and (
            not policy.permits_auto_merge(decision.candidate.score)
        ):
            raise BelowThresholdError(
                f"merge refused: score {decision.candidate.score:.3f} is below "
                f"{policy.name!r} merge threshold {policy.merge_threshold:.3f}"
            )


def apply_decision(
    model: "DomainModel",
    decision: MatchDecisionV1,
    *,
    policy: MatchPolicy | None = None,
    at: datetime | None = None,
):
    """Apply a recorded decision to the entity registry.

    This is the **only** sanctioned bridge from decisions to registry
    merges/splits:

    * ``match`` → :meth:`DomainModel.merge` — gated by
      :func:`_enforce_merge_gate` (evidence + policy + threshold).
      The lower-sorted (older-prefix is irrelevant; deterministic) id of
      the pair is the survivor by default, so application is
      reproducible.
    * ``split`` → :meth:`DomainModel.split` moving exactly
      ``decision.split_assertion_ids``.
    * ``non_match`` / ``uncertain`` → **no registry mutation** (returns
      ``None``); the decision itself is the deliverable.

    Returns the surviving entity for merges, the new entity for splits,
    and ``None`` otherwise.
    """
    # Local import: matching contracts sit *above* the entity registry.
    from irc_data.domain.entities import DomainModel  # noqa: F401

    when = _utc(at) if at else datetime.now(timezone.utc)

    if decision.decision == DecisionType.MATCH.value:
        _enforce_merge_gate(decision, policy)
        survivor_id, removed_id = decision.candidate.pair_key
        return model.merge(
            survivor_id,
            removed_id,
            at=when,
            reason=f"match decision {decision.id} ({decision.threshold_policy})",
        )

    if decision.decision == DecisionType.SPLIT.value:
        # Split the entity the named assertions currently live on.  For a
        # reversal that is normally the survivor of the merge being undone
        # (the decision candidate's other side); fall back to ``left_id``
        # for a first-time split of a never-merged entity.
        candidate_ids = set(decision.candidate.pair_key)
        holder_id = decision.candidate.left_id
        if decision.reversal_of is not None:
            # Undoing a merge: the assertions to move live on the *survivor*
            # of the merge.  Find the merged-away side and follow its
            # ``merged_into`` pointer to the survivor (bypassing the liveness
            # check — the removed entity is preserved precisely so this
            # audit trail remains reachable).
            survivor_id: str | None = None
            for eid in candidate_ids:
                entity = model.get(eid)  # no liveness filter on purpose
                if entity.merged_into:
                    survivor_id = entity.merged_into
                    break
            if survivor_id is not None:
                holder_id = survivor_id
            else:
                # No merge to undo on either side — prefer whichever side
                # actually holds the named assertions.
                wanted = set(decision.split_assertion_ids)
                for eid in candidate_ids:
                    entity = model.get(eid)
                    if wanted <= {ref.assertion_id for ref in entity.assertions}:
                        holder_id = eid
                        break
        new_entity = model.split(
            holder_id,
            assertion_ids=decision.split_assertion_ids,
            at=when,
            reason=f"split decision {decision.id} ({decision.threshold_policy})",
        )
        # Resurrection path: undoing a merge means the wrongly-merged hull
        # already *has* an entity (it was never deleted — only stamped
        # removed).  Transfer the split-off assertions onto it, clear its
        # removal, and discard the transient shell so the original id is
        # live again with full lineage.  The assertion rows themselves are
        # re-keyed (new content-addressed ids), never deleted — the same
        # information-preserving semantics as merge/split.
        if decision.reversal_of is not None:
            removed_id = next(
                (eid for eid in candidate_ids if eid != holder_id), None
            )
            removed = model.get(removed_id) if removed_id else None
            if removed is not None and removed.merged_into == holder_id:
                import dataclasses as _dc

                from irc_data.domain.entities import SourceAssertionRef

                for ref in list(new_entity.assertions):
                    assertion = model._assertions[ref.assertion_id]
                    rekeyed = _dc.replace(
                        assertion, entity_key=removed.entity_key, assertion_id=""
                    )
                    del model._assertions[ref.assertion_id]
                    model._assertions[rekeyed.assertion_id] = rekeyed
                    new_entity.assertions.remove(ref)
                    removed.assertions.append(
                        SourceAssertionRef(
                            assertion_id=rekeyed.assertion_id,
                            field=rekeyed.field,
                            recorded_at=rekeyed.recorded_at,
                            valid_from=rekeyed.valid_from,
                            source_slug=rekeyed.source_slug,
                        )
                    )
                removed.removed_at = None
                removed.merged_into = None
                removed.split_from = holder_id
                # Discard the transient shell so no orphan entity remains.
                del model._entities[new_entity.entity_id]
                return removed
        return new_entity

    # non_match / uncertain: explainable no-ops.  The stored decision is
    # what future candidate generators consult; the registry is untouched.
    return None


# ---------------------------------------------------------------------------
# Reversal — correction without deletion
# ---------------------------------------------------------------------------


def reverse_decision(
    original: MatchDecisionV1,
    *,
    actor: str,
    actor_kind: ActorKind | str,
    policy: MatchPolicy,
    evidence: Iterable[EvidenceRef] = (),
    decided_at: datetime | None = None,
    rationale: str = "",
    split_assertion_ids: Iterable[str] = (),
) -> MatchDecisionV1:
    """Build the decision that *reverses* ``original`` without deleting it.

    The reversal of a ``match`` is a ``split``; the reversal of a
    ``split`` or a ``non_match`` is a fresh ``match`` (re-asserting the
    pair) — which must itself pass :func:`decide`'s policy checks and the
    merge gate when applied.  Reversing an ``uncertain`` decision yields
    the corrected verdict the caller supplies via ``split_assertion_ids``
    semantics — by default a ``non_match``.

    The new decision carries ``supersedes=original.decision_id`` and
    ``reversal_of=original.decision_id``; :meth:`MatchJournal.record`
    stamps the original's ``superseded_by`` link.  Both rows live
    side-by-side in the journal — history is appended, never rewritten.
    """
    if original.decision == DecisionType.MATCH.value:
        verdict = DecisionType.SPLIT
    elif original.decision == DecisionType.UNCERTAIN.value:
        verdict = DecisionType.NON_MATCH
    else:  # non_match or split → re-assert the pair
        verdict = DecisionType.MATCH
    return decide(
        original.candidate,
        verdict,
        actor=actor,
        actor_kind=actor_kind,
        policy=policy,
        evidence=evidence,
        decided_at=decided_at,
        rationale=rationale or f"reversal of {original.id}",
        split_assertion_ids=split_assertion_ids,
        supersedes=original.id,
        reversal_of=original.id,
    )


# ---------------------------------------------------------------------------
# MatchJournal — the append-only decision store
# ---------------------------------------------------------------------------


class MatchJournal:
    """Append-only, in-memory journal of candidates and match decisions.

    Persistence rows can be produced with :meth:`snapshot`; the journal
    semantics mirror the DP-03-02 assertion store:

    * decisions are immutable once recorded;
    * supersession is bitemporal — :meth:`decision_as_of` reproduces the
      effective verdict for any prior system time;
    * nothing is ever deleted, so every merge is reversible by appending
      a reversal decision and applying it.
    """

    def __init__(self) -> None:
        self._candidates: dict[str, CandidatePairV1] = {}
        self._decisions: dict[str, MatchDecisionV1] = {}
        #: candidate_id → ordered decision ids (the supersession chain).
        self._chain: dict[str, list[str]] = {}

    # -- Recording ---------------------------------------------------------------

    def record_candidate(self, candidate: CandidatePairV1) -> str:
        self._candidates[candidate.candidate_id] = candidate
        return candidate.candidate_id

    def record(self, decision: MatchDecisionV1) -> str:
        """Append a decision, linking any superseded predecessor."""
        cid = decision.candidate.candidate_id
        if decision.candidate.candidate_id not in self._candidates:
            self.record_candidate(decision.candidate)
        if decision.supersedes:
            prev = self._decisions.get(decision.supersedes)
            if prev is None:
                raise DecisionStateError(
                    f"superseded decision {decision.supersedes!r} is not in the journal"
                )
            self._decisions[prev.id] = prev.superseded(decision)
        self._decisions[decision.id] = decision
        self._chain.setdefault(cid, []).append(decision.id)
        return decision.id

    def reverse(
        self,
        decision_id: str,
        *,
        actor: str,
        actor_kind: ActorKind | str,
        policy: MatchPolicy,
        evidence: Iterable[EvidenceRef] = (),
        decided_at: datetime | None = None,
        rationale: str = "",
        split_assertion_ids: Iterable[str] = (),
    ) -> MatchDecisionV1:
        """Append (and return) the reversal of a recorded decision."""
        original = self._decisions[decision_id]
        if original.is_superseded:
            raise DecisionStateError(
                f"decision {decision_id!r} is already superseded by "
                f"{original.superseded_by!r}"
            )
        reversal = reverse_decision(
            original,
            actor=actor,
            actor_kind=actor_kind,
            policy=policy,
            evidence=evidence,
            decided_at=decided_at,
            rationale=rationale,
            split_assertion_ids=split_assertion_ids,
        )
        self.record(reversal)
        return reversal

    # -- Queries -----------------------------------------------------------------

    def get(self, decision_id: str) -> MatchDecisionV1:
        return self._decisions[decision_id]

    def candidate(self, candidate_id: str) -> CandidatePairV1:
        return self._candidates[candidate_id]

    def decisions_for(self, candidate_id: str) -> tuple[MatchDecisionV1, ...]:
        """The full supersession chain for one candidate, oldest first."""
        return tuple(self._decisions[i] for i in self._chain.get(candidate_id, ()))

    def current_decision(
        self, candidate_id: str, *, as_of: datetime | None = None
    ) -> MatchDecisionV1 | None:
        """The decision currently in force for a candidate.

        With ``as_of``, reproduces what was in force at that system time:
        only decisions with ``decided_at <= as_of`` are known, and a
        supersession counts only once ``superseded_at <= as_of`` — so a
        later correction never rewrites the past.
        """
        when = _utc(as_of) if as_of else None
        chain = self._chain.get(candidate_id, ())
        current: MatchDecisionV1 | None = None
        for did in chain:
            d = self._decisions[did]
            if when is not None and not d.known_at(when):
                continue
            current = d
        # Walk back through supersessions that were already in force at
        # ``when``: the last *known* decision whose supersession was *not
        # yet* in force is the effective one.
        if when is not None:
            for did in chain:
                d = self._decisions[did]
                if not d.known_at(when):
                    break
                if d.superseded_at is not None and d.superseded_at <= when:
                    continue  # superseded by then — keep walking
                return d
        return current

    def open_candidates(self) -> tuple[CandidatePairV1, ...]:
        """Candidates with no current decision (the review queue)."""
        return tuple(
            c
            for cid, c in self._candidates.items()
            if self.current_decision(cid) is None
        )

    # -- Persistence ---------------------------------------------------------------

    def snapshot(self) -> dict[str, Any]:
        """Serialise the journal (candidates + full decision chains)."""
        return {
            "schema_version": SCHEMA_VERSION,
            "candidates": [c.to_dict() for c in self._candidates.values()],
            "decisions": [d.to_dict() for d in self._decisions.values()],
            "chains": {cid: list(ids) for cid, ids in self._chain.items()},
        }


