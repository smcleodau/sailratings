#: Version tag embedded in every serialised candidate and decision.
SCHEMA_VERSION = "match-decision-v1"


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------


class CandidateStatus(str, enum.Enum):
    """Lifecycle of an identity candidate pair.

    ``OPEN``
        Generated by blocking/scoring, awaiting a decision.
    ``DECIDED``
        A current (non-superseded) decision exists for this pair.
    ``SUPERSEDED``
        The decision this candidate was decided by has itself been
        superseded — the pair is back in limbo (or re-decided by the
        successor decision, which references the same pair).
    """

    OPEN = "open"
    DECIDED = "decided"
    SUPERSEDED = "superseded"


class DecisionType(str, enum.Enum):
    """The four verdicts a match decision can record.

    ``MATCH``
        The two entities are the same real-world thing; the registry may
        merge them (subject to the evidence + policy gate).
    ``NON_MATCH``
        The two entities are distinct; the registry must keep them
        separate.  Stored so a future candidate generator can see the
        pair was *considered and rejected* (and by whom, on what
        evidence) instead of silently re-merging.
    ``UNCERTAIN``
        Neither match nor non-match could be justified under policy.
        Never merges; routes the pair to human review.
    ``SPLIT``
        The entities are *currently one* (previously merged, or one
        entity double-counting two real-world things) and must be split
        apart.  Carries ``split_assertion_ids`` naming exactly which
        assertion references move to the resurrected entity.
    """

    MATCH = "match"
    NON_MATCH = "non_match"
    UNCERTAIN = "uncertain"
    SPLIT = "split"


class ActorKind(str, enum.Enum):
    """Who (or what) took a match decision."""

    #: A deterministic rule (``rule_version`` identifies which).
    AUTO_RULE = "auto_rule"
    #: A statistical/ML model (``model_version`` identifies which).
    MODEL = "model"
    #: A human steward (``actor`` carries the steward's id/name).
    HUMAN = "human"


#: Allowed decision strings (mirrors any future DB check constraint).
DECISIONS: tuple[str, ...] = tuple(d.value for d in DecisionType)


